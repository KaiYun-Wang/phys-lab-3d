## 核心公式

### 连续性方程（不可压缩、稳定流）

A₁v₁ = A₂v₂

因此：v₂ = v₁ / (A₂/A₁)

截面越小，流速越大。

### 伯努利方程（水平、理想流体近似）

P₁ + ½ρv₁² = P₂ + ½ρv₂²

### 压强差

ΔP = P₁ − P₂ = ½ρ(v₂² − v₁²)

- ρ：流体密度
- 收缩管（v₂ > v₁）：ΔP > 0，即 P₂ < P₁，喉部静压更低
- 扩张管（v₂ < v₁）：ΔP < 0，下游静压相对更高

测压管液面高度差与压强差成正比，可用于定性读取 ΔP。

